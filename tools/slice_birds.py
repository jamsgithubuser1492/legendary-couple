"""Cuts Sheet WX2 (art/source/sheet_wx2_flying_life.jpg): sparrow, gull and butterfly flight loops.
Run:  python3 tools/slice_birds.py   Writes wx2_* sprites and src/game/spriteListBirds.ts.
The creature only: the card edge and the ground shadow ellipse are left out (the game draws its own soft shadow).
Every loop shares one canvas size and anchor, so wing flaps never make the body jitter."""
import importlib.util, json, os
import numpy as np
from PIL import Image
from scipy import ndimage

HERE = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location('s41', os.path.join(HERE, 'slice_sheets41_45.py'))
s41 = importlib.util.module_from_spec(spec); spec.loader.exec_module(s41)
ROOT, OUT = s41.ROOT, s41.OUT
SH = s41.Sheet('sheet_wx2_flying_life.jpg')
SPARROW_X = [(30, 155), (157, 285), (285, 413), (413, 540)]
GULL_X = [(562, 687), (690, 815), (817, 943), (946, 1072)]
PINK_X = [(30, 153), (157, 283), (287, 413), (415, 540)]
BLUE_X = GULL_X


def outline_cut(x0, y0, x1, y1, thr=200):
    """For cream bodied birds the card colour is too close to the belly, so the silhouette comes from the brown
    outline instead: close it, fill it in and keep the largest piece."""
    crop = SH.img.crop((x0, y0, x1, y1))
    a = np.array(crop).astype(int)
    dark = a.mean(-1) < thr  # the brown outline only: the cream belly is as pale as the card, and the shadow is paler still
    padded = np.pad(dark, 10)  # so the closing can reach round the edge of the crop
    m = ndimage.binary_closing(padded, iterations=7)[10:-10, 10:-10]
    m = ndimage.binary_fill_holes(m)
    lab, n = ndimage.label(m)
    if n > 1:
        sizes = ndimage.sum(m, lab, range(1, n + 1))
        m = lab == (1 + int(np.argmax(sizes)))
    m = ndimage.binary_dilation(m, iterations=1)
    # the soft ground shadow has no dark outline, so nothing below the lowest outlined pixel (the feet) belongs to the bird
    rows = np.where(dark.sum(1) > 0)[0]
    if len(rows):
        m[rows.max() + 2:] = False
    al = (m * 255).astype(np.uint8)
    return Image.fromarray(np.dstack([a.astype(np.uint8), al]), 'RGBA')


def frames(xs, y0, y1, outline=False, thr=200):
    out = []
    for x0, x1 in xs:
        im = outline_cut(x0 + 9, y0, x1 - 9, y1, thr) if outline else SH.cutbox('o', x0 + 9, y0, x1 - 9, y1)
        bb = im.getchannel('A').point(lambda v: 255 if v > 8 else 0).getbbox()
        out.append(im.crop(bb))
    return out


# In the game the map scale is about 32 px to the metre (a 54 px person is about 1.7 m). Wingspans: sparrow about 9 px
# (a little under 30 cm), gull about 34 px (a bit over a metre), butterfly about 6 px. Sprites are saved at twice that
# size so they stay crisp on high resolution screens, and the game draws them at scale 0.5.
TARGET = {'sparrow': 20, 'gull': 68, 'bfly': 13}


def shrink(im, kind, ref_w):
    k = TARGET[kind] / ref_w
    return im.resize((max(1, round(im.width * k)), max(1, round(im.height * k))), Image.LANCZOS)


def same_canvas(ims):
    """Pad every frame to the largest size, centred, so the loop keeps one anchor."""
    w, h = max(i.width for i in ims), max(i.height for i in ims)
    res = []
    for i in ims:
        c = Image.new('RGBA', (w, h), (0, 0, 0, 0))
        c.paste(i, ((w - i.width) // 2, (h - i.height) // 2), i)
        res.append(c)
    return res


def main():
    jobs = []
    sets = {'sparrow': ('sparrow', frames(SPARROW_X, 100, 216, True)), 'gull': ('gull', frames(GULL_X, 106, 206)),
            'bfly_pink': ('bfly', frames(PINK_X, 455, 548)), 'bfly_blue': ('bfly', frames(BLUE_X, 455, 548))}
    for k, (kind, ims) in sets.items():
        ims = same_canvas(ims)
        ref = ims[0].width
        for n, im in enumerate(ims, 1):
            jobs.append((f'wx2_{k}_{n}', shrink(im, kind, ref)))
    sref = same_canvas(frames(SPARROW_X, 100, 216, True))[0].width
    pose = frames(SPARROW_X, 748, 858, True, 172)
    for k, im in zip(('perch', 'up', 'flap', 'glide'), pose):
        jobs.append((f'wx2_sparrow_{k}', shrink(im, 'sparrow', sref)))
    entries = []
    for key, im in jobs:
        im.save(os.path.join(OUT, key + '.png'), optimize=True)
        entries.append({'key': key, 'file': key + '.png', 'w': im.width, 'h': im.height, 'dw': max(2, round(im.width / 2))})
    with open(os.path.join(ROOT, 'src', 'game', 'spriteListBirds.ts'), 'w') as f:
        f.write('// Generated by tools/slice_birds.py. Do not edit by hand.\n')
        f.write('export const BIRD_SPRITES = ' + json.dumps(entries, indent=2) + ' as const;\n')
    print('wrote', len(entries))


if __name__ == '__main__':
    main()
