"""Cuts the café crew stills (sheets 110 to 114, saved as art/source/sheet_crew_*.jpg).
Run:  python3 tools/slice_crew.py   Writes crew_<id>_<level>_<view> sprites and src/game/spriteListCrew.ts.
Each look has a front and a back figure on the sheets; the right facing views are the left facing ones mirrored.
The sheets have mislabelled cells, so every figure is picked by hand below (see PICK)."""
import importlib.util, json, os
import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location('s41', os.path.join(HERE, 'slice_sheets41_45.py'))
s41 = importlib.util.module_from_spec(spec); spec.loader.exec_module(s41)
ROOT, OUT = s41.ROOT, s41.OUT
SHEETS = {k: s41.Sheet(f'sheet_crew_{k}.jpg') for k in ('tan_pip', 'oren_juno', 'maya_ollie', 'hana_kenji')}
X = [(70, 140), (180, 250), (340, 408), (452, 520), (606, 676), (718, 788), (875, 940), (985, 1050)]
FRONT, BACK = (144, 270), (270, 388)


def top(col, back=False):
    return (X[col][0], (BACK if back else FRONT)[0], X[col][1], (BACK if back else FRONT)[1])


# (sheet, character, level) -> (front box, back box); a box may name another look to borrow from
BIG_FRONT, BIG_BACK = (68, 775, 142, 932), (172, 775, 242, 932)  # the first pair of the big expert rotation block at the bottom of a sheet
PICK = {
    ('tan_pip', 'tan', 1): (top(0), top(0, True)), ('tan_pip', 'tan', 2): (top(2), top(2, True)), ('tan_pip', 'tan', 3): (top(3), top(3, True)),
    ('tan_pip', 'pip', 1): (top(4), top(4, True)), ('tan_pip', 'pip', 2): (top(5), top(5, True)), ('tan_pip', 'pip', 3): (top(7), top(7, True)),
    ('oren_juno', 'oren', 1): (top(0), top(0, True)), ('oren_juno', 'oren', 2): (top(2), top(2, True)), ('oren_juno', 'oren', 3): (top(3), top(3, True)),
    # a back of None means the sheet's "back" figure still shows a face, so the front is used for both
    ('oren_juno', 'juno', 1): (top(4), None), ('oren_juno', 'juno', 2): (top(5), None), ('oren_juno', 'juno', 3): (BIG_FRONT, BIG_BACK),
    ('maya_ollie', 'maya', 1): (top(0), None), ('maya_ollie', 'maya', 2): (top(2), None), ('maya_ollie', 'maya', 3): ((187, 470, 249, 586), (187, 586, 246, 696)),
    ('maya_ollie', 'ollie', 1): (top(4), None), ('maya_ollie', 'ollie', 2): (top(5), None), ('maya_ollie', 'ollie', 3): (BIG_FRONT, BIG_BACK),
    ('hana_kenji', 'hana', 1): (top(0), None), ('hana_kenji', 'hana', 2): (top(2), top(2, True)), ('hana_kenji', 'hana', 3): ((78, 468, 136, 585), (78, 588, 136, 696)),
    ('hana_kenji', 'kenji', 1): (top(4), None), ('hana_kenji', 'kenji', 2): (top(5), None), ('kenji_x', 'kenji', 3): None,
}
PICK.pop(('kenji_x', 'kenji', 3))
PICK[('hana_kenji', 'kenji', 3)] = (BIG_FRONT, BIG_BACK)


def main():
    entries = []

    def save(key, im, dw_h=54):
        bb = im.getchannel('A').point(lambda v: 255 if v > 8 else 0).getbbox()
        if bb:
            im = im.crop(bb)
        im.save(os.path.join(OUT, key + '.png'), optimize=True)
        entries.append({'key': key, 'file': key + '.png', 'w': im.width, 'h': im.height, 'dw': round(im.width * dw_h / im.height)})

    for (sheet, who, lvl), (fb, bb) in PICK.items():
        sh = SHEETS[sheet]
        front = sh.cutbox('o', fb[0] - 2, fb[1] - 2, fb[2] + 2, fb[3] + 2)
        back = sh.cutbox('o', bb[0] - 2, bb[1] - 2, bb[2] + 2, bb[3] + 2) if bb else front
        save(f'crew_{who}_{lvl}_fl', front)
        save(f'crew_{who}_{lvl}_fr', front.transpose(Image.FLIP_LEFT_RIGHT))
        save(f'crew_{who}_{lvl}_bl', back)
        save(f'crew_{who}_{lvl}_br', back.transpose(Image.FLIP_LEFT_RIGHT))
    with open(os.path.join(ROOT, 'src', 'game', 'spriteListCrew.ts'), 'w') as f:
        f.write('// Generated by tools/slice_crew.py. Do not edit by hand.\n')
        f.write('export const CREW_SPRITES = ' + json.dumps(entries, indent=2) + ' as const;\n')
    print('wrote', len(entries))


if __name__ == '__main__':
    main()
