"""Cuts the weather sheet WX1 (art/source/sheet_wx1_weather.jpg): 8 firefly swarm frames, 4 rain and 4 snow overlay frames.
Run:  python3 tools/slice_weather.py   Writes wx_firefly_1..8, wx_rain_1..4, wx_snow_1..4 and src/game/spriteListWeather.ts.
Every tile is drawn on dark navy. The navy is removed by treating the pixel as light added over the navy: the alpha comes from
how far a pixel is above the navy and the colour is what is left, so soft glows keep their falloff when drawn over a map."""
import json, os
import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'public', 'assets', 'sprites')
SRC = np.array(Image.open(os.path.join(ROOT, 'art', 'source', 'sheet_wx1_weather.jpg')).convert('RGB')).astype(float)
NAVY = np.array([30, 41, 60], float)
INSET = 14  # the tiles have rounded corners and a paper edge: stay well inside


def lift(box, gain=150.0, brighten=0.0):
    x0, y0, x1, y1 = box
    a = SRC[y0 + INSET:y1 - INSET, x0 + INSET:x1 - INSET]
    d = np.clip(a - NAVY, 0, None)
    lit = d.max(-1)
    alpha = np.clip(lit / gain, 0, 1) ** 0.8
    safe = np.maximum(alpha, 1e-3)[..., None]
    rgb = np.clip((a - NAVY * (1 - alpha[..., None])) / safe, 0, 255)  # undo the navy underneath, so edges keep their own colour
    rgb = rgb + (np.array([238, 246, 255], float) - rgb) * brighten  # snow and rain read as white light over a pale map
    alpha[lit < 6] = 0  # jpeg noise on the flat navy
    return Image.fromarray(np.dstack([rgb, alpha * 255]).astype(np.uint8), 'RGBA')


FIRE = [(31, 102, 280, 240), (297, 102, 546, 240), (563, 102, 805, 240), (821, 102, 1071, 240),
        (30, 272, 280, 410), (297, 271, 546, 410), (563, 271, 804, 410), (821, 272, 1071, 410)]
RAIN = [(52, 487, 277, 658), (317, 487, 542, 658), (576, 486, 801, 658), (835, 487, 1060, 658)]
SNOW = [(57, 736, 274, 907), (320, 736, 537, 907), (581, 736, 797, 907), (838, 736, 1055, 907)]


def main():
    entries = []

    def save(key, im, dw):
        im.save(os.path.join(OUT, key + '.png'), optimize=True)
        entries.append({'key': key, 'file': key + '.png', 'w': im.width, 'h': im.height, 'dw': dw})

    frames = [lift(b) for b in FIRE]
    boxes = [f.getchannel('A').point(lambda v: 255 if v > 10 else 0).getbbox() for f in frames]
    bb = (min(b[0] for b in boxes), min(b[1] for b in boxes), max(b[2] for b in boxes), max(b[3] for b in boxes))  # one box for all 8, so the pulse never shifts
    for i, f in enumerate(frames, 1):
        save(f'wx_firefly_{i}', f.crop(bb), 120)
    for i, b in enumerate(RAIN, 1):
        im = lift(b, 120.0, 0.35)
        save(f'wx_rain_{i}', im.crop((0, 0, im.width, im.height - 24)), 100)  # the little ground splashes at the foot of the tile are left out: they would repeat in rows
    for i, b in enumerate(SNOW, 1):
        save(f'wx_snow_{i}', lift(b, 110.0, 0.5), 100)
    with open(os.path.join(ROOT, 'src', 'game', 'spriteListWeather.ts'), 'w') as f:
        f.write('// Generated by tools/slice_weather.py. Do not edit by hand.\n')
        f.write('export const WEATHER_SPRITES = ' + json.dumps(entries, indent=2) + ' as const;\n')
    print('wrote', len(entries), [(e['key'], e['w'], e['h']) for e in entries])


if __name__ == '__main__':
    main()
