"""Cuts the Matcha Masters backdrop (the painted counter scene, without the feature cards under it).
Run:  python3 tools/slice_matcha_bg.py   Writes mg_bg_matcha.jpg and src/game/spriteListBackdrops.ts."""
import json, os
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'public', 'assets', 'sprites')
im = Image.open(os.path.join(ROOT, 'art', 'source', 'matcha_backdrop.jpg')).convert('RGB').crop((0, 0, 1085, 688))
im.save(os.path.join(OUT, 'mg_bg_matcha.jpg'), quality=88)
entries = [{'key': 'mg_bg_matcha', 'file': 'mg_bg_matcha.jpg', 'w': im.width, 'h': im.height, 'dw': 960}]
with open(os.path.join(ROOT, 'src', 'game', 'spriteListBackdrops.ts'), 'w') as f:
    f.write('// Generated by tools/slice_matcha_bg.py. Do not edit by hand.\n')
    f.write('export const BACKDROP_SPRITES = ' + json.dumps(entries, indent=2) + ' as const;\n')
print('wrote', len(entries))
