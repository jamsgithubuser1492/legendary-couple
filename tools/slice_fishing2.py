"""Cuts the second Stellar Fishing batch: the rod upgrade path and tackle pieces (sheet 92, art/source/sheet_fish_rods.jpg)
and the fish swim frames, splash rings and pier props (sheet 93, art/source/sheet_fish_anim.jpg).
Run:  python3 tools/slice_fishing2.py   Writes sf2_* sprites and src/game/spriteListFish2.ts.
Both sheets are 1264 x 843. The animation sheet's "8 frame" loops only draw 2 or 3 frames, and a few of those frames are a
different colour variant of the fish, so each frame below was picked by hand against the finished sprite (sf_<species>)."""
import importlib.util, json, os
import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location('s41', os.path.join(HERE, 'slice_sheets41_45.py'))
s41 = importlib.util.module_from_spec(spec); spec.loader.exec_module(s41)
ROOT, OUT = s41.ROOT, s41.OUT
SH = {'rods': s41.Sheet('sheet_fish_rods.jpg'), 'anim': s41.Sheet('sheet_fish_anim.jpg')}
jobs = []  # (key, image, display width, keep canvas)


def cut(sh, key, box, dw, pad=3, keep_all=False):
    x0, y0, x1, y1 = box
    jobs.append((key, SH[sh].cutbox('o', x0 - pad, y0 - pad, x1 + pad, y1 + pad, keep_all=keep_all), dw, False))


def keyed(sh, key, box, dw):
    """Lifts light blue rings and spray off their beige card: alpha follows how much bluer a pixel is than the card."""
    a = np.array(SH[sh].img.crop(box).convert('RGB')).astype(int)
    r, g, b = a[..., 0], a[..., 1], a[..., 2]
    al = np.clip((b - r - 6) * 11, 0, 255)
    out = np.dstack([a, al]).astype(np.uint8)
    jobs.append((key, Image.fromarray(out, 'RGBA'), dw, False))


def loop(species, boxes, dw):
    """A swim loop: every frame is cut with the same canvas (the union box, feet and nose where they were on the sheet)."""
    x0 = min(b[0] for b in boxes); y0 = min(b[1] for b in boxes)
    w = max(b[2] - b[0] for b in boxes) + 6; h = max(b[3] - b[1] for b in boxes) + 6
    for i, b in enumerate(boxes, 1):
        im = SH['anim'].cutbox('o', b[0] - 3, b[1] - 3, b[2] + 3, b[3] + 3)
        bb = im.getchannel('A').point(lambda v: 255 if v > 8 else 0).getbbox()
        im = im.crop(bb)
        canvas = Image.new('RGBA', (w + 8, h + 8), (0, 0, 0, 0))
        canvas.alpha_composite(im, ((canvas.width - im.width) // 2, (canvas.height - im.height) // 2))
        jobs.append((f'sf2_{species}_{i}', canvas, dw, True))


def main():
    # ---- rods (sheet 92): the three tiers, each at rest and as the cast arc with its line and hook where one is drawn
    for key, box in {'bamboo': (28, 128, 147, 176), 'faithful': (165, 126, 280, 177), 'carbon': (450, 127, 572, 175),
                     'deepsea': (583, 124, 699, 179), 'stardust': (861, 127, 978, 177), 'pearl': (994, 125, 1108, 178), 'kraken': (1122, 121, 1235, 176)}.items():
        cut('rods', f'sf2_rod_{key}', box, 60)
    cut('rods', 'sf2_rodarc_bamboo', (32, 212, 145, 289), 60, keep_all=True)
    cut('rods', 'sf2_rodarc_stardust', (861, 217, 978, 294), 60, keep_all=True)
    cut('rods', 'sf2_rodarc_kraken', (1123, 213, 1235, 293), 60, keep_all=True)
    # tackle: reels, lures, glowing bobbers and hook (the sheet 92 section 2 and 3)
    for key, box in {'reel_classic': (466, 397, 516, 468), 'bobber_cork': (703, 368, 723, 404)}.items():
        pass
    # ---- fish swim loops (sheet 93)
    loop('salmon', [(28, 287, 106, 318), (109, 287, 183, 318), (187, 287, 260, 318)], 70)
    loop('carp', [(35, 342, 102, 375), (110, 342, 178, 375)], 66)
    loop('angel', [(115, 397, 178, 432), (188, 397, 252, 432)], 60)
    loop('nudi', [(40, 453, 100, 485), (110, 453, 175, 485), (182, 453, 248, 485)], 62)
    loop('crab', [(662, 285, 722, 322), (745, 285, 808, 322)], 56)
    loop('perch', [(660, 347, 725, 382), (745, 347, 810, 382)], 62)
    loop('grouper', [(742, 405, 812, 435)], 68)
    # ---- splash rings and spray (sheet 93 section 3, light blue on beige cards)
    for i, x in enumerate([(838, 568, 910, 636), (920, 568, 990, 636), (1002, 568, 1072, 636), (1082, 568, 1153, 636)], 1):
        keyed('anim', f'sf2_ring_{i}', x, 64)
    keyed('anim', 'sf2_splash_star', (1164, 568, 1235, 636), 64)
    for i, x in enumerate([(838, 671, 910, 739), (922, 671, 995, 739), (1005, 671, 1078, 739)], 1):
        keyed('anim', f'sf2_spray_{i}', x, 64)

    entries = []
    for key, im, dw, canvas in jobs:
        if not canvas:
            bb = im.getchannel('A').point(lambda v: 255 if v > 8 else 0).getbbox()
            if bb:
                im = im.crop(bb)
        im.save(os.path.join(OUT, key + '.png'), optimize=True)
        entries.append({'key': key, 'file': key + '.png', 'w': im.width, 'h': im.height, 'dw': dw})
    with open(os.path.join(ROOT, 'src', 'game', 'spriteListFish2.ts'), 'w') as f:
        f.write('// Generated by tools/slice_fishing2.py. Do not edit by hand.\n')
        f.write('export const FISH2_SPRITES = ' + json.dumps(entries, indent=2) + ' as const;\n')
    print('wrote', len(entries))


if __name__ == '__main__':
    main()
