"""Cuts one front facing standing sprite per companion outfit from the outfit sheets (60 to 64).

Boxes are in sheet pixels. cutbox() floods the pale sheet background away from the box edges.
Run:  python3 tools/slice_outfits.py
Writes public/assets/sprites/outfit_*.png and src/game/spriteListOutfits.ts.
"""
import importlib.util, json, os
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location('s41', os.path.join(HERE, 'slice_sheets41_45.py'))
s41 = importlib.util.module_from_spec(spec)
spec.loader.exec_module(s41)
ROOT, OUT = s41.ROOT, s41.OUT

# display height in game pixels for each companion, so the new looks match the old ones
HEIGHT = {'kitty': 38, 'miffy': 46, 'snoopy': 49}

# (key, companion, sheet, box)
CUTS = [
    ('outfit_miffy_winter', 'miffy', 'miffy3', (445, 88, 535, 218)),
    ('outfit_miffy_date', 'miffy', 'miffy3', (445, 220, 535, 348)),
    ('outfit_miffy_concert', 'miffy', 'miffy3', (440, 358, 545, 488)),
    ('outfit_miffy_holiday', 'miffy', 'miffy3', (445, 538, 535, 672)),
    ('outfit_miffy_beach', 'miffy', 'miffy2', (435, 85, 535, 218)),
    ('outfit_miffy_barista', 'miffy', 'miffy2', (435, 224, 535, 352)),
    ('outfit_miffy_golden', 'miffy', 'miffy2', (440, 538, 535, 672)),
    ('outfit_miffy_pajamas', 'miffy', 'miffy1', (712, 235, 795, 348)),
    ('outfit_kitty_winter', 'kitty', 'kitty3', (445, 92, 540, 218)),
    ('outfit_kitty_garden', 'kitty', 'kitty3', (440, 224, 545, 348)),
    ('outfit_kitty_chef', 'kitty', 'kitty3', (445, 350, 545, 482)),
    ('outfit_kitty_jogger', 'kitty', 'kitty3', (445, 548, 545, 678)),
    ('outfit_snoopy_beach', 'snoopy', 'snoopy', (1000, 92, 1085, 212)),
    ('outfit_snoopy_barista', 'snoopy', 'snoopy', (1000, 214, 1085, 296)),
    ('outfit_snoopy_date', 'snoopy', 'snoopy', (332, 526, 392, 598)),
    ('outfit_snoopy_concert', 'snoopy', 'snoopy', (330, 598, 395, 672)),
    ('outfit_snoopy_rain', 'snoopy', 'snoopy', (543, 530, 603, 604)),
    ('outfit_snoopy_chef', 'snoopy', 'snoopy', (440, 738, 545, 915)),
    ('outfit_snoopy_jogger', 'snoopy', 'snoopy', (640, 760, 725, 915)),
]
SHEETS = {
    'miffy3': 'sheet_miffy_outfits3.jpg', 'miffy2': 'sheet_miffy_outfits2.jpg', 'miffy1': 'sheet_miffy_outfits1.jpg',
    'kitty3': 'sheet_kitty_outfits3.jpg', 'snoopy': 'sheet_snoopy_outfits.jpg',
}


def main():
    sheets = {k: s41.Sheet(v) for k, v in SHEETS.items()}
    entries = []
    for key, comp, sh, box in CUTS:
        im = sheets[sh].cutbox('o', *box)
        bb = im.getchannel('A').point(lambda v: 255 if v > 8 else 0).getbbox()
        if bb:
            im = im.crop(bb)
        hh = HEIGHT[comp] * 2
        im = im.resize((max(1, round(im.width * hh / im.height)), hh), Image.LANCZOS)
        im.save(os.path.join(OUT, key + '.png'), optimize=True)
        entries.append({'key': key, 'file': key + '.png', 'w': im.width, 'h': im.height, 'dw': round(im.width / 2)})
    with open(os.path.join(ROOT, 'src', 'game', 'spriteListOutfits.ts'), 'w') as f:
        f.write('// Generated by tools/slice_outfits.py. Do not edit by hand.\n')
        f.write('export const OUTFIT_SPRITES = ' + json.dumps(entries, indent=2) + ' as const;\n')
    print('wrote', len(entries))


if __name__ == '__main__':
    main()
