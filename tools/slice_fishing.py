"""Cuts the Stellar Fishing art: 8 new fish species (sheet 94), pier backdrops, tackle and splash art (sheet 91).
Run:  python3 tools/slice_fishing.py   Writes sf_* sprites and src/game/spriteListFish.ts."""
import importlib.util, json, os
from PIL import Image, ImageDraw
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location('s41', os.path.join(HERE, 'slice_sheets41_45.py'))
s41 = importlib.util.module_from_spec(spec); spec.loader.exec_module(s41)
ROOT, OUT = s41.ROOT, s41.OUT
S = {'fish': s41.Sheet('sheet_fish_species.jpg'), 'tackle': s41.Sheet('sheet_fish_tackle.jpg')}
jobs = []


def one(key, sh, box, dw, pad=10, keep_all=False):
    x0, y0, x1, y1 = box
    jobs.append((key, S[sh].cutbox('o', x0 - pad, y0 - pad, x1 + pad, y1 + pad, keep_all=keep_all), dw))


def plain(key, sh, box, dw):
    jobs.append((key, S[sh].img.crop(box).convert('RGBA'), dw))


R1, R2 = (120, 176), (216, 280)
FISH = {  # key: (box, display width)
    'salmon': ((34, R1[0], 141, R1[1]), 70), 'carp': ((169, R1[0], 269, R1[1]), 66), 'angel': ((41, R2[0], 134, R2[1]), 60), 'nudi': ((462, R1[0], 550, R1[1]), 62), 'crab': ((472, R2[0], 550, R2[1]), 56),
    'perch': ((591, R2[0], 681, R2[1]), 62), 'grouper': ((859, R1[0], 959, R1[1]), 68),
    'eel': ((866, R2[0], 950, R2[1]), 56), }


def badge(sh, box, radius=12):
    """A tile of the sheet worn as a round water bubble, so no square card edges show on the pier water."""
    im = S[sh].img.crop(box).convert('RGBA')
    m = Image.new('L', im.size, 0)
    ImageDraw.Draw(m).ellipse((0, 0, im.width - 1, im.height - 1), fill=255)
    im.putalpha(m)
    return im


def splash(box):
    """A splash lifted off its beige tile: the beige is keyed out, the blue white water stays."""
    a = np.array(S['tackle'].img.crop(box).convert('RGBA')).astype(int)
    r, b = a[..., 0], a[..., 2]
    a[..., 3] = np.clip((b - r + 4) * 28, 0, 255)
    return Image.fromarray(a.astype(np.uint8), 'RGBA')


BOBBERS = {'cork': (144, 215), 'shell': (252, 324), 'glow': (361, 431)}
FRAMES = {'': (742, 811), '_bite': (827, 896)}  # floating, then the bite pulse


def main():
    for k, (b, dw) in FISH.items():
        one(f'sf_{k}', 'fish', b, dw, pad=6)
    # pier backdrops: the horizontal cross sections, trimmed inside their rounded frames
    plain('sf_bg_day', 'tackle', (26, 146, 568, 349), 480)
    plain('sf_bg_golden', 'tackle', (27, 384, 352, 540), 480)
    plain('sf_bg_night', 'tackle', (27, 584, 352, 755), 480)
    for k, (y0, y1) in BOBBERS.items():
        for suffix, (x0, x1) in FRAMES.items():
            jobs.append((f'sf_bobber_{k}{suffix}', badge('tackle', (x0, y0, x1, y1)), 46))
    jobs.append(('sf_splash', splash((617, 831, 674, 886)), 64))
    jobs.append(('sf_ring_a', splash((891, 745, 940, 794)), 60))
    jobs.append(('sf_ring_b', splash((1015, 745, 1064, 794)), 60))
    entries = []
    for key, im, dw in jobs:
        bb = im.getchannel('A').point(lambda v: 255 if v > 8 else 0).getbbox()
        if bb:
            im = im.crop(bb)
        want = dw * 2
        if im.width != want:
            im = im.resize((want, max(1, round(im.height * want / im.width))), Image.LANCZOS)
        if key.startswith('sf_bg_'):
            im.convert('RGB').save(os.path.join(OUT, key + '.jpg'), quality=88)
            entries.append({'key': key, 'file': key + '.jpg', 'w': im.width, 'h': im.height, 'dw': dw})
        else:
            im.save(os.path.join(OUT, key + '.png'), optimize=True)
            entries.append({'key': key, 'file': key + '.png', 'w': im.width, 'h': im.height, 'dw': dw})
    with open(os.path.join(ROOT, 'src', 'game', 'spriteListFish.ts'), 'w') as f:
        f.write('// Generated by tools/slice_fishing.py. Do not edit by hand.\n')
        f.write('export const FISH_SPRITES = ' + json.dumps(entries, indent=2) + ' as const;\n')
    print('wrote', len(entries))


if __name__ == '__main__':
    main()
