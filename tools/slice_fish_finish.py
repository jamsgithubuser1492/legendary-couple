"""Cuts the Stellar Fishing finish scene: the night pier backdrop and the James and Rachel casting frames.
Run:  python3 tools/slice_fish_finish.py   Writes sf_fin_* sprites and src/game/spriteListFinish.ts."""
import importlib.util, json, os
import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location('s41', os.path.join(HERE, 'slice_sheets41_45.py'))
s41 = importlib.util.module_from_spec(spec); spec.loader.exec_module(s41)
ROOT, OUT = s41.ROOT, s41.OUT
CAST = s41.Sheet('sheet_fish_cast.jpg')
entries = []


def add(key, im, dw, jpg=False):
    if not jpg:
        bb = im.getchannel('A').point(lambda v: 255 if v > 8 else 0).getbbox()
        if bb:
            im = im.crop(bb)
    ext = 'jpg' if jpg else 'png'
    if jpg:
        im.convert('RGB').save(os.path.join(OUT, f'{key}.jpg'), quality=86)
    else:
        im.save(os.path.join(OUT, f'{key}.png'), optimize=True)
    entries.append({'key': key, 'file': f'{key}.{ext}', 'w': im.width, 'h': im.height, 'dw': dw})


def tidy(im, box, erase=()):
    """Clears the paper showing inside the rod loops and strays (the map inset) that touch a frame."""
    a = np.array(im).astype(int)
    rgb = a[..., :3]
    paper = ((rgb.max(-1) - rgb.min(-1)) < 28) & (rgb.mean(-1) > 228)
    a[..., 3] = np.where(paper, 0, a[..., 3])
    x0, y0 = box[0] - 3, box[1] - 3
    for ex0, ey0, ex1, ey1 in erase:
        a[max(0, ey0 - y0):max(0, ey1 - y0), max(0, ex0 - x0):max(0, ex1 - x0), 3] = 0
    return Image.fromarray(a.astype(np.uint8), 'RGBA')


def main():
    bg = Image.open(os.path.join(ROOT, 'art', 'source', 'fishing_night_backdrop.jpg')).convert('RGB')
    band = bg.crop((0, 215, 1085, 640))  # lighthouse, lit pier and the water line, wide and short for the result card
    add('sf_fin_bg', band, 480, jpg=True)
    rows = {
        'james_init': (166, 318, [(71, 179), (314, 419), (532, 680), (800, 898)], False),
        'rachel_init': (362, 493, [(76, 211), (325, 459), (571, 705), (813, 947)], False),
        'james_rel': (546, 683, [(66, 300), (322, 540), (560, 790), (810, 1000)], True),
        'rachel_rel': (731, 868, [(80, 240), (325, 492), (570, 738), (818, 982)], False),
    }
    for k, (y0, y1, xs, keep) in rows.items():
        for i, (x0, x1) in enumerate(xs, 1):
            if k == 'james_init' and i != 3:
                continue  # the other three have a pale loop or the map inset behind them
            im = CAST.cutbox('o', x0 - 3, y0 - 3, x1 + 3, y1 + 3, keep_all=keep)
            add(f'sf_fin_{k}_{i}', tidy(im, (x0, y0)), 60)
    with open(os.path.join(ROOT, 'src', 'game', 'spriteListFinish.ts'), 'w') as f:
        f.write('// Generated by tools/slice_fish_finish.py. Do not edit by hand.\n')
        f.write('export const FINISH_SPRITES = ' + json.dumps(entries, indent=2) + ' as const;\n')
    print('wrote', len(entries))


if __name__ == '__main__':
    main()
