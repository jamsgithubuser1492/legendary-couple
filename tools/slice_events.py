"""Cuts the café event art: sheet E1 (string lights, rain, signs, bunting, accents) and sheet E2 (adoption pen, pets,
toy basket, power tile, laptop clutter, Wi-Fi owl, record player, chai barrel, chalkboard).
Run:  python3 tools/slice_events.py   Writes ev_* sprites and src/game/spriteListEvents.ts.
Pieces on the cream paper are cut with Sheet.cutbox (flood from the box edge). Lights and rain sit on dark navy tiles,
so those are keyed by their difference from the tile colour: only the glow and streaks remain."""
import importlib.util, json, os
import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location('s41', os.path.join(HERE, 'slice_sheets41_45.py'))
s41 = importlib.util.module_from_spec(spec); spec.loader.exec_module(s41)
ROOT, OUT = s41.ROOT, s41.OUT
E1, E2 = s41.Sheet('event_e1_overlays.jpg'), s41.Sheet('event_e2_props.jpg')
jobs = []  # (key, image, dw, trim)


def cut(sh, key, box, dw, keep_all=False, pad=3):
    x0, y0, x1, y1 = box
    jobs.append((key, sh.cutbox('o', x0 - pad, y0 - pad, x1 + pad, y1 + pad, keep_all=keep_all), dw, True))


def navy(sh, key, box, dw, inset=0, gain=5, floor=22, trim=True):
    """A glow or streak layer lifted off its navy tile: alpha follows how far each pixel is from the tile colour."""
    x0, y0, x1, y1 = box
    a = np.array(sh.img.crop((x0 + inset, y0 + inset, x1 - inset, y1 - inset)).convert('RGB')).astype(int)
    bg = np.median(np.concatenate([a[2:6].reshape(-1, 3), a[-6:-2].reshape(-1, 3)]), axis=0)
    d = np.abs(a - bg).max(-1)
    al = np.clip((d - floor) * gain, 0, 255)
    jobs.append((key, Image.fromarray(np.dstack([a, al]).astype(np.uint8), 'RGBA'), dw, trim))


def main():
    # ---- sheet E1
    navy(E1, 'ev_lights_warm', (50, 137, 265, 298), 107, inset=2)
    navy(E1, 'ev_lights_pastel', (50, 365, 265, 540), 107, inset=2)
    navy(E1, 'ev_lights_mix', (50, 637, 272, 898), 111, inset=2)
    navy(E1, 'ev_rain_soft', (325, 137, 540, 298), 215, inset=8, trim=False)
    navy(E1, 'ev_rain_diag', (322, 365, 545, 540), 223, inset=8, trim=False)
    navy(E1, 'ev_rain_drops', (323, 637, 547, 898), 224, inset=8, trim=False)
    cut(E1, 'ev_sign_study', (595, 140, 820, 250), 70)
    cut(E1, 'ev_sign_adopt', (632, 305, 773, 395), 44)
    cut(E1, 'ev_sign_jazz', (617, 452, 790, 590), 50)
    cut(E1, 'ev_bunting_pink', (598, 632, 812, 725), 107)
    cut(E1, 'ev_bunting_sage', (598, 740, 812, 812), 107)
    cut(E1, 'ev_bunting_sky', (598, 842, 812, 910), 107)
    cut(E1, 'ev_notes', (905, 150, 1030, 245), 40, keep_all=True)
    cut(E1, 'ev_sparkles', (870, 310, 1058, 400), 40, keep_all=True)
    cut(E1, 'ev_confetti_1', (865, 462, 960, 540), 40, keep_all=True)
    cut(E1, 'ev_confetti_2', (962, 462, 1058, 540), 40, keep_all=True)
    # ---- sheet E2
    cut(E2, 'ev_pen', (60, 95, 330, 295), 110)
    cut(E2, 'ev_pets', (415, 90, 770, 285), 90, keep_all=True)
    cut(E2, 'ev_toy_basket', (868, 125, 1030, 285), 34)
    cut(E2, 'ev_power_tile', (55, 400, 330, 575), 54)
    cut(E2, 'ev_laptop', (438, 372, 725, 572), 56, keep_all=True)
    cut(E2, 'ev_wifi_owl', (845, 390, 1050, 560), 24, keep_all=True)
    cut(E2, 'ev_record_player', (65, 695, 300, 880), 46)
    cut(E2, 'ev_chai_barrel', (460, 655, 670, 880), 40)
    cut(E2, 'ev_chalkboard', (838, 618, 1042, 862), 40)

    entries = []
    for key, im, dw, trim in jobs:
        if trim:
            bb = im.getchannel('A').point(lambda v: 255 if v > 8 else 0).getbbox()
            if bb:
                im = im.crop(bb)
        im.save(os.path.join(OUT, key + '.png'), optimize=True)
        entries.append({'key': key, 'file': key + '.png', 'w': im.width, 'h': im.height, 'dw': dw})
    with open(os.path.join(ROOT, 'src', 'game', 'spriteListEvents.ts'), 'w') as f:
        f.write('// Generated by tools/slice_events.py. Do not edit by hand.\n')
        f.write('export const EVENT_SPRITES = ' + json.dumps(entries, indent=2) + ' as const;\n')
    print('wrote', len(entries))


if __name__ == '__main__':
    main()
