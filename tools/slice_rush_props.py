"""Cuts the Rush Hour props sheet (art/source/rush_props_clutter.jpg) for the later Café Rush Hour Manager build. Not wired yet.
Run:  python3 tools/slice_rush_props.py   Writes rush_* sprites and src/game/spriteListRush.ts (export RUSH_SPRITES).
Boxes were found with the outline detector and picked by eye. Sizes: an isometric tile is 64 px wide on screen, so a crate is
about 40 px wide, the storehouse about 110 px, a pitcher or tamper about 22 px and the table clutter about 50 px."""
import importlib.util, json, os
import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location('s41', os.path.join(HERE, 'slice_sheets41_45.py'))
s41 = importlib.util.module_from_spec(spec); spec.loader.exec_module(s41)
ROOT, OUT = s41.ROOT, s41.OUT
SH = s41.Sheet('rush_props_clutter.jpg')

# key: (box, on screen width). The empty crate on the sheet is drawn in four views; the ingredient icon is added in code.
PIECES = {
    'rush_crate_ne': ((28, 181, 151, 302), 40), 'rush_crate_se': ((168, 181, 291, 302), 40),
    'rush_crate_nw': ((309, 181, 431, 301), 40), 'rush_crate_sw': ((448, 178, 571, 299), 40),
    'rush_storehouse_full': ((622, 152, 832, 487), 110), 'rush_storehouse_empty': ((867, 155, 1060, 469), 101),
    'rush_pitcher_a': ((57, 570, 151, 724), 22), 'rush_pitcher_b': ((217, 570, 312, 725), 22),
    'rush_pitcher_c': ((368, 553, 462, 725), 22), 'rush_pitcher_d': ((514, 570, 608, 724), 22),
    'rush_stanchion': ((57, 808, 197, 937), 56), 'rush_sign': ((246, 804, 342, 938), 36),
    'rush_table_clutter': ((440, 782, 659, 931), 50),
    'rush_tamper_ne': ((742, 649, 804, 745), 22), 'rush_tamper_se': ((862, 649, 925, 745), 22),
    'rush_tamper_nw': ((983, 649, 1045, 745), 22), 'rush_tamper_sw': ((764, 802, 823, 897), 22),
}


def clear_paper(im, lum=198, spread=48):
    """Removes the grid paper showing through the open frame of the empty shelves (the edge flood cannot reach it)."""
    a = np.array(im).astype(int)
    rgb = a[..., :3]
    paper = (rgb.min(-1) > lum) & ((rgb.max(-1) - rgb.min(-1)) < spread)
    a[..., 3] = np.where(paper, 0, a[..., 3])
    return Image.fromarray(a.astype(np.uint8), 'RGBA')


def glow_tamper():
    """The glowing reward state sits on bare paper: a solid tamper body on top of a soft golden halo rebuilt from the paper difference."""
    x0, y0, x1, y1 = 940, 790, 1022, 915
    crop = SH.img.crop((x0, y0, x1, y1)).convert('RGB')
    a = np.array(crop).astype(int)
    ring = np.concatenate([a[0], a[-1], a[:, 0], a[:, -1]])
    bg = np.median(ring, axis=0)
    halo = np.clip((np.abs(a - bg).max(-1) - 6) * 5, 0, 200)
    h, w = halo.shape
    yy, xx = np.mgrid[0:h, 0:w]
    edge = np.minimum(np.minimum(xx, w - 1 - xx), np.minimum(yy, h - 1 - yy))
    halo = halo * np.clip(edge / 16.0, 0, 1)  # fade out before the crop edge so no square shows
    gold = np.zeros_like(a)
    gold[..., 0], gold[..., 1], gold[..., 2] = 255, 214, 110
    out = Image.fromarray(np.dstack([gold, halo]).astype(np.uint8), 'RGBA')
    body = SH.cutbox('o', 952 - 4, 809 - 4, 1011 + 4, 901 + 4)
    out.alpha_composite(body, (952 - 4 - x0, 809 - 4 - y0))
    return out


def main():
    entries = []

    def save(key, im, dw):
        bb = im.getchannel('A').point(lambda v: 255 if v > 8 else 0).getbbox()
        if bb:
            im = im.crop(bb)
        im.save(os.path.join(OUT, key + '.png'), optimize=True)
        entries.append({'key': key, 'file': key + '.png', 'w': im.width, 'h': im.height, 'dw': dw})

    for key, (b, dw) in PIECES.items():
        im = SH.cutbox('o', b[0] - 4, b[1] - 4, b[2] + 4, b[3] + 4, keep_all=key.startswith(('rush_stanchion', 'rush_storehouse')))
        save(key, clear_paper(im) if key == 'rush_storehouse_empty' else im, dw)
    save('rush_tamper_glow', glow_tamper(), 26)
    with open(os.path.join(ROOT, 'src', 'game', 'spriteListRush.ts'), 'w') as f:
        f.write('// Generated by tools/slice_rush_props.py. Do not edit by hand.\n')
        f.write('export const RUSH_SPRITES = ' + json.dumps(entries, indent=2) + ' as const;\n')
    print('wrote', len(entries))


if __name__ == '__main__':
    main()
